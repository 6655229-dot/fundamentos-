# ciclo_for_range.py
print("--- DEMOSTRACIÓN DE BUCLE FOR Y RANGE ---")

print("\nEjemplo 1: Contando del 1 al 5 (range de 1 a 6 de forma exclusiva):")
for i in range(1, 6):
    print(f"Iteración número: {i}")

print("\nEjemplo 2: Conteo regresivo del 3 al 1:")
for j in range(3, 0, -1):
    print(f"Cuenta regresiva: {j}")
    
print("\n¡Ciclo FOR finalizado!")